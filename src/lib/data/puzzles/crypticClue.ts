// Thai upper/lower vowels and tone marks share their base letter's box.
export function letterBoxes(text: string): string[] {
	return Array.from(text.normalize('NFC').replace(/\s/g, '')).reduce<string[]>((boxes, character) => {
		if (/[\u0E31\u0E34-\u0E3A\u0E47-\u0E4E]/u.test(character) && boxes.length) boxes[boxes.length - 1] += character;
		else boxes.push(character);
		return boxes;
	}, []);
}

