import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
 await page.goto('http://localhost:5192/puzzles/puzzle-clicker', { waitUntil: 'domcontentloaded', timeout: 60000 });
 const tap = page.getByRole('button', { name: 'ต่อชิ้นจิ๊กซอว์', exact: true });
 await expect(tap).toBeEnabled();
 await tap.focus(); await page.keyboard.press('Space');
 await expect(page.getByTestId('piece-balance')).toHaveText('1');
 for (let i = 0; i < 14; i++) await tap.click();
 await page.getByRole('button', { name: 'ซื้อผู้ช่วยแกะคำใบ้ ราคา 15 ชิ้น', exact: true }).click();
 await expect(page.getByText('+0.2 ชิ้น/วินาที · มี 1', { exact: true })).toBeVisible();
 await expect.poll(async () => Number(await page.getByTestId('piece-balance').textContent())).toBeGreaterThan(0.1);
 await page.evaluate(() => window.dispatchEvent(new Event('pagehide')));
 await page.reload({ waitUntil: 'domcontentloaded' });
 await expect(tap).toBeEnabled();
 await expect(page.getByText('+0.2 ชิ้น/วินาที · มี 1', { exact: true })).toBeVisible();
 await page.getByRole('button', { name: 'เริ่มใหม่', exact: true }).click();
 await page.getByRole('button', { name: 'ยกเลิก', exact: true }).click();
 await expect(page.getByText('+0.2 ชิ้น/วินาที · มี 1', { exact: true })).toBeVisible();
 if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Mobile overflow');
 await page.screenshot({ path: 'scratch/puzzle-clicker-mobile.png', fullPage: true });
 await page.setViewportSize({ width: 1280, height: 900 });
 await page.screenshot({ path: 'scratch/puzzle-clicker-desktop.png', fullPage: true });
 await page.getByRole('button', { name: 'เริ่มใหม่', exact: true }).click();
 await page.getByRole('button', { name: 'ยืนยันเริ่มใหม่', exact: true }).click();
 await expect(page.getByTestId('piece-balance')).toHaveText('0');
 await expect(page.getByRole('button', { name: 'ซื้อผู้ช่วยแกะคำใบ้ ราคา 15 ชิ้น', exact: true })).toBeDisabled();
 if (errors.length) throw new Error(errors.join('\n'));
 console.log('Passed: keyboard and pointer clicks, purchase, passive income, reload, reset confirmation, mobile layout; no page errors.');
} finally { await browser.close(); }
